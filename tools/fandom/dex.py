"""Build data/dex.js: the full Tandor Pokédex (untrusted wiki data parsed as text, never executed).
Inputs: cache/Pok_dex.json (list order), cache/dex_list_parsed.json (numbers/types from the rendered list),
cache/<Species>.json (evolution box + Availability), data/book.js locs (where the binder lists it).
Patch-note corrections (2026 Patch Notes) are applied last with a citation."""
import json,re,os,sys
sys.path.insert(0,os.path.dirname(os.path.abspath(__file__)))
from build import clean,templates,split,kv,slug,page,url
H=os.path.dirname(os.path.abspath(__file__)); APP=os.path.abspath(H+'/../..')
PATCH='https://pokemon-uranium.fandom.com/wiki/2026_Patch_Notes'
rows=json.load(open(H+'/cache/dex_list_parsed.json'))
B=json.loads(open(APP+'/data/book.js').read()[len('window.BOOK='):].rstrip().rstrip(';'))
where={}
for l in B['locs']:
  for w in l['wild']:
    lab=w.get('label') or 'Wild'
    e=where.setdefault(w['key'],{})
    e.setdefault(l['id'],{'loc':l['id'],'name':l['name'],'labels':[]})
    if lab not in e[l['id']]['labels'] and len(e[l['id']]['labels'])<3: e[l['id']]['labels'].append(lab)
PNOTES={
 'minyan':'1.4.0: can now hold Black Sludge.',
 'duplicat':'1.4.0: Quick Powder and Metal Powder now work on it.',
 'tikiki':'1.4.0: now gives 1 Attack EV.','frikitiki':'1.4.0: now gives 2 Attack EVs.',
 'actan':'1.4.0: respawns daily if you have not caught it.',
 'buizel':'1.4.0b: the Hidden Grotto Buizel now has Soak.',
 'drilgann':'1.4.0: Mega Drilgann\'s ability is now correctly Sand Rush.',
}
def evo(w):
  for name in ('TwoStageMega','Evobox-3','Evobox-2','Evobox','ThreeStageMega','Evobox-1','Evobox-3Mega','Evobox-2Mega','EvoboxEevee','Evobox-branch'):
    pass
  m=re.search(r'==\s*Evolution\s*==(.*?)(?:\n==[^=])',w,re.S)
  if not m: return []
  sec=m.group(1); ts=templates(sec,'') if False else None
  i=sec.find('{{')
  if i<0: return []
  body=None
  for _,b in templates(sec, sec[i+2:].split('\n')[0].split('|')[0].strip()):
    body=b; break
  if not body: return []
  _,n=kv(split(body))
  out=[]
  keys=sorted({k[4:] for k in n if k.startswith('name') and k[4:]}, key=lambda s:(len(s),s))
  for k in keys:
    nm=clean(n.get('name'+k,'')).strip("'")
    if not nm: continue
    how=clean(re.sub(r'<br\s*/?>',' ',n.get('evo'+k,''))); how=re.sub(r'File:([^.]*?)\.(?:png|gif|jpg)\d*',lambda m:' (day) ' if 'Day Icon' in m.group(1) else ' (night) ' if 'Night Icon' in m.group(1) else ' ',how); how=re.sub(r'\s+',' ',how).strip()
    no=clean(n.get('no'+k,''))
    out.append({'name':nm,'no':no,'how':how,'mega':nm.lower().startswith('mega ')})
  return out
def avail(w):
  for _,b in templates(w,'Availability'):
    _,n=kv(split(b)); parts=[]
    for k,lab in (('common','Common'),('uncommon','Uncommon'),('rare','Rare'),('one','One-time'),('none','Other')):
      v=clean(re.sub(r'<br\s*/?>',', ',n.get(k,''))); v=re.sub(r'\s+',' ',v).strip(' ,')
      if v: parts.append(f'{lab}: {v}')
    j=' · '.join(parts); j=re.sub(r'(\d*)File:Bag ([A-Za-z ]+?) Sprite\.png',lambda m:(' '+m.group(1)+' '+m.group(2)+(',' if True else '')),j)
    j=re.sub(r'File:[^ ]*\.(png|gif)','',j); j=re.sub(r'\s+',' ',j).strip(' ,')
    return j[:260]
  return ''
dex=[];missing=[]
for r in rows:
  p=page(r['name'])
  w=(p or {}).get('wikitext','') if p and not p.get('missing') else ''
  if not w: missing.append(r['name'])
  k=slug(r['name'])
  e={'n':r['n'],'name':r['name'],'key':k,'t':list(dict.fromkeys(r['types'])),'evo':evo(w) if w else [],'avail':avail(w) if w else '',
     'where':list(where.get(k,{}).values()),'url':url(r['page'] if r.get('page') else r['name']),'rev':(p or {}).get('revid')}
  if k in PNOTES: e['patch']={'text':PNOTES[k],'src':PATCH}
  dex.append(e)
open(APP+'/data/dex.js','w').write('/* Tandor Pokédex: facts from pokemon-uranium.fandom.com (CC BY-SA 3.0), patch notes applied. Generated by tools/fandom/dex.py */\nwindow.DEX='+json.dumps(dex,ensure_ascii=False,separators=(',',':'))+';')
import collections
print('entries',len(dex),'missing pages',missing)
print('nuclear',sum('Nuclear' in d['t'] for d in dex),'with evo',sum(bool(d['evo']) for d in dex),'with binder locs',sum(bool(d['where']) for d in dex),'with avail text',sum(bool(d['avail']) for d in dex),'patched',sum('patch' in d for d in dex))
keys={d['key'] for d in dex}
unk=sorted({w['key'] for l in B['locs'] for w in l['wild']}-keys); print('binder wild keys not in dex',unk)
